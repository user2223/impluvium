use super::env::BUILD_ONLY;
use super::fields::{FIELDS, Fallback, Field, Presence};
use super::model::LOOPBACK_DESCRIPTION;
use super::secret::MAX_BYTES;

const INTRO: &str = "<!-- SPDX-FileCopyrightText: 2026 the impluvium contributors -->
<!-- SPDX-License-Identifier: AGPL-3.0-only -->
<!-- Generated by `impluvium-server config reference` from server/crates/server-bin/src/config/fields.rs. Do not edit by hand. -->

# Server configuration

The server reads its configuration from environment variables. It reads no configuration file.
Check a configuration with `impluvium-server config check`: the command validates the environment, prints the effective settings without secrets and exits. It starts no listener, opens no database connection and runs no migration.

## Variables

";

/// Words for a list of code names: `a`, `b` and `c`.
fn code_list(names: &[&str]) -> String {
    let quoted: Vec<String> = names.iter().map(|name| format!("`{name}`")).collect();
    match quoted.split_last() {
        Some((last, rest)) if !rest.is_empty() => format!("{} and {last}", rest.join(", ")),
        _ => quoted.join(", "),
    }
}

/// The text after the table. The fixed values come from the code that
/// enforces them.
fn outro() -> String {
    let build_only = code_list(&BUILD_ONLY);
    format!(
"
## Secrets

A secret can be given directly or through a file. For `DATABASE_URL`, set either the variable itself or `DATABASE_URL_FILE` with the path of a file that holds the value, such as a container secret.
Setting both is an error. The file must be a regular file of at most {MAX_BYTES} bytes, readable by the server, valid UTF-8 and not empty. One trailing line break is removed.

## Validation

- The external origin has a scheme, a host and optionally a port, but no path, query or credentials. A plain `http` origin is accepted only for this machine ({LOOPBACK_DESCRIPTION}) or when `IMPLUVIUM_INSECURE_LAN` is `true`. Use `https` otherwise; the server itself may sit behind a TLS proxy and speak plain http to it.
- Paths must be absolute.
- A trusted proxy is a network such as `192.0.2.10/32` (a single IPv4 address) or `2001:db8::10/128` (a single IPv6 address), with no bits set below the prefix length. List the addresses of your proxies only, with `/32` or `/128`, and not whole networks: every machine in a trusted network can set the client address of its requests.  The prefix length 0 is refused because it would trust every address, and so is any network inside the IPv4-mapped range `::ffff:0:0/96`: write IPv4 networks in IPv4 notation.
- The pool minimum must not exceed the pool maximum.
- `IMPLUVIUM_BACKUP_COMMAND` is required when `IMPLUVIUM_BACKUP_MODE` is `command` and refused otherwise. It is a JSON array with the program first; the server starts it without a shell. Do not put secrets into the arguments: `config check` shows only the program and one placeholder per argument.
- Booleans are exactly `true` or `false`. Names are case-sensitive.
- Error messages name the variable and the rule. They never repeat a value.

## Unknown variables

Every variable that starts with `IMPLUVIUM_` and is not listed above is an error, and the message suggests the closest known name. This catches typos and names of features that the server does not read yet. The variables {build_only} belong to the build and are ignored.
The server does not accept the variable names of earlier releases as aliases.
",
    )
}

fn row(field: &Field) -> String {
    let file = match field.file_variable {
        Some(name) => format!("`{name}`"),
        None => "-".to_owned(),
    };
    let required = match field.presence {
        Presence::Required => "yes",
        Presence::Optional => "no",
    };
    let default = match field.fallback {
        Fallback::None => "none".to_owned(),
        Fallback::Value(text) => format!("`{text}`"),
        Fallback::Described(text) => text.to_owned(),
    };
    format!(
        "| `{}` | {} | {} | {} | {} | {} |\n",
        field.variable,
        file,
        field.kind.describe(),
        required,
        default,
        field.summary
    )
}

/// The complete page.
pub fn render() -> String {
    let mut page = String::from(INTRO);
    page.push_str("| Variable | File variant | Type | Required | Default | Description |\n");
    page.push_str("|---|---|---|---|---|---|\n");
    for field in FIELDS {
        page.push_str(&row(field));
    }
    page.push_str(&outro());
    page
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_committed_page_matches_the_field_table() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../../docs/admin/configuration.md"
        );
        let committed = std::fs::read_to_string(path).expect("read the committed reference");
        assert!(
            committed == render(),
            "docs/admin/configuration.md is out of date; regenerate it with \
             `impluvium-server config reference`"
        );
    }

    #[test]
    fn every_field_has_a_row_and_a_clean_summary() {
        let page = render();
        for field in FIELDS {
            assert!(page.contains(&format!("| `{}` |", field.variable)));
            assert!(!field.summary.contains('|'), "{}", field.variable);
            assert!(!field.summary.is_empty());
            assert_eq!(field.is_secret(), field.file_variable.is_some());
        }
    }

    #[test]
    fn defaults_parse_with_their_own_kind() {
        for field in FIELDS {
            if let Fallback::Value(text) = field.fallback {
                let parsed = super::super::model::parse(field.kind, text);
                assert!(parsed.is_ok(), "default of {} is invalid", field.variable);
            }
        }
    }

    #[test]
    fn only_secrets_have_file_variants_and_variables_are_unique() {
        let mut seen = Vec::new();
        for field in FIELDS {
            for name in [Some(field.variable), field.file_variable]
                .into_iter()
                .flatten()
            {
                assert!(!seen.contains(&name), "{name} appears twice");
                seen.push(name);
            }
            if field.file_variable.is_some() {
                assert_eq!(field.kind, super::super::fields::Kind::DatabaseUrl);
            }
        }
    }
}
