    /// Whether the field is optional (`name?:`) and its type text, from a ts-rs declaration.
    fn field(declaration: &str, name: &str) -> Option<(bool, String)> {
        declaration.match_indices(name).find_map(|(at, _)| {
            let before = declaration[..at].chars().next_back();
            if before.is_some_and(|c| c.is_alphanumeric() || c == '_') {
                return None;
            }
            let rest = &declaration[at + name.len()..];
            let (optional, rest) = match rest.strip_prefix('?') {
                Some(rest) => (true, rest),
                None => (false, rest),
            };
            let value = rest.strip_prefix(": ")?;
            let end = value.find(',').unwrap_or(value.len());
            Some((optional, value[..end].trim().to_owned()))
        })
    }

    fn assert_field(declaration: &str, name: &str, optional: bool, accepted: &[&str]) {
        let (found_optional, found) =
            field(declaration, name).unwrap_or_else(|| panic!("no field {name} in {declaration}"));
        assert_eq!(found_optional, optional, "{name}: {declaration}");
        assert!(
            accepted.contains(&found.as_str()),
            "{name}: {found:?} is not one of {accepted:?}"
        );
    }

