//! The TypeScript export of the wire shapes.
//!
//! The shape roots are listed once in `shape_roots!` below. ts-rs writes the
//! declaration of each root and of everything it mentions into a directory;
//! [`assemble`] turns those files into the final set (one header, LF line
//! endings, the runtime enum constants and an index) and
//! refuses name collisions. `cargo xtask api-types` writes that set to
//! `server/shared/api/shapes/` or, with `--check`, fails on any difference.
//! The roots, the imports between the files and the names all come from ts-rs
//! and the type visitors; nothing is listed by hand except the roots.
//!
//! Shapes carry no raw 64-bit integers: ts-rs would declare them as `bigint`, but the JSON
//! number that serde writes is not one. Use `DecU64` and `DecI64`; [`declared_names`] and
//! [`assemble`] refuse the raw types.

use std::any::TypeId;
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::num::{NonZeroI64, NonZeroI128, NonZeroIsize, NonZeroU64, NonZeroU128, NonZeroUsize};
use std::path::Path;

use ts_rs::{Config, TS, TypeVisitor};

use crate::enums::runtime_enums;
use crate::error::ApiError;
use crate::json::JsonValue;
use crate::page::{CursorPage, PageQuery};

/// First lines of every exported file.
const HEADER: &str = "// SPDX-FileCopyrightText: 2026 the impluvium contributors\n\
// SPDX-License-Identifier: AGPL-3.0-only\n\
\n\
// Generated by `cargo xtask api-types`. Do not edit; CI fails when this file and the Rust types differ.\n";

/// Name of the file with the runtime constants.
pub const RUNTIME_FILE: &str = "runtime.ts";
/// Name of the index file.
pub const INDEX_FILE: &str = "index.ts";

/// A list of shape roots.
trait Roots {
    /// Calls the visitor once for every root.
    fn visit_all(visitor: &mut impl TypeVisitor);
}

/// Declares a list of roots. Generic roots appear once, with a placeholder
/// argument: the TypeScript declaration of a generic type does not depend on it.
macro_rules! shape_roots {
    ($name:ident: $($ty:ty),+ $(,)?) => {
        struct $name;

        impl Roots for $name {
            fn visit_all(visitor: &mut impl TypeVisitor) {
                $(visitor.visit::<$ty>();)+
            }
        }
    };
}

shape_roots!(
    ShapeRoots:
    ApiError,
    crate::enums::Platform,
    JsonValue,
    PageQuery,
    crate::page::Page<String>,
    CursorPage<String>,
);

/// Writes the declarations of every root to `directory` with ts-rs.
pub fn export_roots(directory: &Path) -> Result<(), String> {
    export_roots_of::<ShapeRoots>(directory)
}

fn export_roots_of<R: Roots>(directory: &Path) -> Result<(), String> {
    struct Exporter<'a> {
        config: &'a Config,
        failure: Option<String>,
    }

    impl TypeVisitor for Exporter<'_> {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if self.failure.is_none()
                && T::output_path().is_some()
                && let Err(error) = T::export_all(self.config)
            {
                self.failure = Some(format!("{}: {error}", T::ident(self.config)));
            }
        }
    }

    std::fs::create_dir_all(directory).map_err(|error| error.to_string())?;
    let config = Config::new().with_out_dir(directory);
    let mut exporter = Exporter {
        config: &config,
        failure: None,
    };
    R::visit_all(&mut exporter);
    exporter.failure.map_or(Ok(()), Err)
}

/// The TypeScript names of the roots in declaration order.
pub fn root_names() -> Vec<String> {
    struct Names<'a>(&'a Config, Vec<String>);

    impl TypeVisitor for Names<'_> {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if T::output_path().is_some() {
                self.1.push(T::ident(self.0));
            }
        }
    }

    let config = Config::new();
    let mut names = Names(&config, Vec::new());
    ShapeRoots::visit_all(&mut names);
    names.1
}

/// The type ids of the integers that ts-rs declares as `bigint`.
fn wide_integers() -> HashSet<TypeId> {
    HashSet::from([
        TypeId::of::<u64>(),
        TypeId::of::<i64>(),
        TypeId::of::<u128>(),
        TypeId::of::<i128>(),
        TypeId::of::<usize>(),
        TypeId::of::<isize>(),
        TypeId::of::<NonZeroU64>(),
        TypeId::of::<NonZeroI64>(),
        TypeId::of::<NonZeroU128>(),
        TypeId::of::<NonZeroI128>(),
        TypeId::of::<NonZeroUsize>(),
        TypeId::of::<NonZeroIsize>(),
    ])
}

/// Checks the types of the roots and of everything they mention: no two
/// different types that ts-rs writes to a file share a TypeScript name, and no
/// raw 64-bit integer occurs. Two instantiations of one generic type (such as
/// `Page<String>` and `Page<Game>`) have the same declaration and are one type
/// here. Returns the sorted names of all types that get a file.
pub fn declared_names() -> Result<Vec<String>, String> {
    declared_names_of::<ShapeRoots>()
}

fn declared_names_of<R: Roots>() -> Result<Vec<String>, String> {
    struct Walker<'a> {
        config: &'a Config,
        seen: HashSet<TypeId>,
        wide: HashSet<TypeId>,
        declarations: HashMap<String, String>,
        failure: Option<String>,
    }

    impl TypeVisitor for Walker<'_> {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if self.failure.is_some() || !self.seen.insert(TypeId::of::<T>()) {
                return;
            }
            if self.wide.contains(&TypeId::of::<T>()) {
                self.failure = Some(
                    "a raw 64-bit integer is used in a shape; use DecU64 or DecI64".to_owned(),
                );
                return;
            }
            if T::output_path().is_some() {
                let name = T::ident(self.config);
                let declaration = T::decl(self.config);
                if let Some(previous) = self.declarations.insert(name.clone(), declaration.clone())
                    && previous != declaration
                {
                    self.failure = Some(format!("two different types are exported as {name}"));
                    return;
                }
            }
            T::visit_dependencies(self);
            T::visit_generics(self);
        }
    }

    let config = Config::new();
    let mut walker = Walker {
        config: &config,
        seen: HashSet::new(),
        wide: wide_integers(),
        declarations: HashMap::new(),
        failure: None,
    };
    R::visit_all(&mut walker);
    match walker.failure {
        Some(failure) => Err(failure),
        None => {
            let mut names: Vec<String> = walker.declarations.into_keys().collect();
            names.sort();
            Ok(names)
        }
    }
}

/// `platformValues` for `Platform`.
fn constant_name(type_name: &str) -> String {
    let mut chars = type_name.chars();
    let first = chars.next().map(|c| c.to_ascii_lowercase());
    first.into_iter().chain(chars).collect::<String>() + "Values"
}

/// The content of `runtime.ts`: one constant array of wire values per runtime enum.
pub fn runtime_ts() -> String {
    let mut enums = runtime_enums();
    enums.sort_by(|a, b| a.name.cmp(b.name));
    let mut text = String::new();
    for entry in &enums {
        text.push_str(&format!(
            "import type {{ {0} }} from \"./{0}\";\n",
            entry.name
        ));
    }
    for entry in &enums {
        let values: Vec<String> = entry.values.iter().map(|v| format!("{v:?}")).collect();
        text.push_str(&format!(
            "\n/** Every value of `{name}`, in the order of the server. */\nexport const {constant} = [{values}] as const satisfies readonly {name}[];\n",
            name = entry.name,
            constant = constant_name(entry.name),
            values = values.join(", ")
        ));
    }
    text
}

/// True when `word` occurs in `text` as a whole word.
fn contains_word(text: &str, word: &str) -> bool {
    text.match_indices(word).any(|(at, _)| {
        let before = text[..at].chars().next_back();
        let after = text[at + word.len()..].chars().next();
        let part = |c: Option<char>| c.is_some_and(|c| c.is_alphanumeric() || c == '_');
        !part(before) && !part(after)
    })
}

/// The text without `/* ... */` blocks (doc comments) and whole-line `//` comments.
fn without_comments(text: &str) -> String {
    let mut code = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("/*") {
        code.push_str(&rest[..start]);
        rest = match rest[start..].find("*/") {
            Some(end) => &rest[start + end + 2..],
            None => "",
        };
    }
    code.push_str(rest);
    code.lines()
        .filter(|line| !line.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Turns the files ts-rs wrote (file name to content) into the final set.
///
/// Refuses odd or colliding file names, a `bigint` in any declaration (a raw 64-bit integer; comments
/// are not scanned) and
/// a runtime constant for an enum that has no file.
pub fn assemble(written: BTreeMap<String, String>) -> Result<BTreeMap<String, String>, String> {
    let mut files = BTreeMap::new();
    let mut stems = BTreeSet::new();
    for (name, content) in written {
        let stem = name
            .strip_suffix(".ts")
            .filter(|stem| {
                !stem.is_empty() && stem.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
            })
            .ok_or_else(|| format!("unexpected file name {name:?}"))?;
        if [RUNTIME_FILE, INDEX_FILE].contains(&name.as_str()) {
            return Err(format!("{name} collides with a generated file"));
        }
        if contains_word(&without_comments(&content), "bigint") {
            return Err(format!(
                "{name} declares a bigint: a raw 64-bit integer is used in a shape; use DecU64 or DecI64"
            ));
        }
        let body = content.replace("\r\n", "\n");
        files.insert(
            name.clone(),
            format!("{HEADER}\n{}\n", body.trim_end_matches('\n')),
        );
        stems.insert(stem.to_owned());
    }
    if let Some(entry) = runtime_enums()
        .iter()
        .find(|entry| !stems.contains(entry.name))
    {
        return Err(format!(
            "runtime.ts needs {0}.ts, but {0} is not exported; make it a shape root",
            entry.name
        ));
    }
    files.insert(
        RUNTIME_FILE.to_owned(),
        format!("{HEADER}\n{}", runtime_ts()),
    );
    let mut index = format!("{HEADER}\n");
    for stem in &stems {
        index.push_str(&format!("export type {{ {stem} }} from \"./{stem}\";\n"));
    }
    index.push_str("export * from \"./runtime\";\n");
    files.insert(INDEX_FILE.to_owned(), index);
    Ok(files)
}

