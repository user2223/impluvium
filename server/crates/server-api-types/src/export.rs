    const REQUIRED_ATTRIBUTES: [&str; 2] =
        ["serde(default", "skip_serializing_if = \"Tri::is_missing\""];

    fn is_identifier(name: &str) -> bool {
        let name = name.strip_prefix("r#").unwrap_or(name);
        !name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
    }

    /// `Tri<..>`, also path-qualified (`tri::Tri<..>`, `crate::tri::Tri<..>`).
    fn is_tri(kind: &str) -> bool {
        kind.contains('<')
            && kind
                .split('<')
                .next()
                .and_then(|head| head.rsplit("::").next())
                == Some("Tri")
    }

    fn strip_visibility(text: &str) -> &str {
        match text.strip_prefix("pub(") {
            Some(rest) => rest
                .split_once(')')
                .map_or(text, |(_, rest)| rest.trim_start()),
            None => text.strip_prefix("pub ").unwrap_or(text),
        }
    }

    /// Splits at commas outside of `<>`, `()` and `[]`.
    fn split_top_level(text: &str) -> Vec<&str> {
        let (mut depth, mut start, mut parts) = (0_i32, 0, Vec::new());
        for (at, c) in text.char_indices() {
            match c {
                '<' | '(' | '[' => depth += 1,
                '>' | ')' | ']' => depth -= 1,
                ',' if depth == 0 => {
                    parts.push(&text[start..at]);
                    start = at + 1;
                }
                _ => {}
            }
        }
        parts.push(&text[start..]);
        parts
    }

    /// Describes every struct field of type `Tri<...>` whose attributes lack `serde(default` or
    /// `skip_serializing_if = "Tri::is_missing"`. Fields are found line by line: attributes are the
    /// `#[` and `///` lines directly above the field. A struct variant on one line
    /// (`V { a: Tri<T> },`) must carry the attributes inside the braces. Unnamed fields of tuple
    /// variants and attributes spread over several lines are not recognised.
    fn tri_fields_missing_attributes(source: &str) -> Vec<String> {
        let lines: Vec<&str> = source.lines().collect();
        let mut bad = Vec::new();
        for (index, line) in lines.iter().enumerate() {
            let text = line.trim();
            if text.starts_with("//") {
                continue;
            }
            let text = strip_visibility(text);
            let mut found = Vec::new();
            if let Some((head, rest)) = text.split_once(" { ")
                && is_identifier(head)
                && let Some((inner, _)) = rest.rsplit_once('}')
            {
                for piece in split_top_level(inner) {
                    let mut piece = piece.trim();
                    let mut attributes = String::new();
                    while piece.starts_with("#[")
                        && let Some(end) = piece.find(']')
                    {
                        attributes.push_str(&piece[..=end]);
                        piece = piece[end + 1..].trim_start();
                    }
                    if let Some((name, kind)) = strip_visibility(piece).split_once(": ")
                        && is_identifier(name)
                        && is_tri(kind)
                    {
                        found.push(attributes);
                    }
                }
            } else if let Some((name, kind)) = text.split_once(": ")
                && is_identifier(name)
                && is_tri(kind)
            {
                let mut attributes = String::new();
                for above in lines[..index].iter().rev().map(|l| l.trim()) {
                    if above.starts_with("#[") || above.starts_with("///") {
                        attributes.push_str(above);
                    } else {
                        break;
                    }
                }
                found.push(attributes);
            }
            for attributes in found {
                if !REQUIRED_ATTRIBUTES.iter().all(|a| attributes.contains(a)) {
                    bad.push(format!("line {}: {text}", index + 1));
                }
            }
        }
        bad
    }

    #[test]
    fn the_tri_guard_flags_a_field_without_the_attributes() {
        let attributes = "    #[serde(default, skip_serializing_if = \"Tri::is_missing\")]\n";
        let optional = "    #[ts(optional = nullable)]\n";
        let fine = [
            format!("{attributes}{optional}    pub a: Tri<String>,\n"),
            format!("{attributes}    a: Tri<String>,\n"),
            format!("{attributes}    pub(crate) a: Tri<String>,\n"),
            format!("{attributes}    pub(super) a: Tri<String>,\n"),
            format!("{attributes}    pub(in crate::x) a: Tri<String>,\n"),
            format!("{attributes}    pub r#type: Tri<String>,\n"),
            format!("{attributes}    pub a: crate::Tri<String>,\n"),
            format!("{attributes}    pub a: tri::Tri<String>,\n"),
            format!("{attributes}    pub a: crate::tri::Tri<String>,\n"),
            format!("{attributes}{optional}    /// Docs.\n    pub a: Tri<String>,\n"),
            "    V { #[serde(default, skip_serializing_if = \"Tri::is_missing\")] a: Tri<u8>, b: u8 },\n"
                .to_owned(),
            "    pub a: Option<Tri>,\n    pub b: Triple<u8>,\n".to_owned(),
        ];
        for source in &fine {
            assert!(tri_fields_missing_attributes(source).is_empty(), "{source}");
        }
        let no_default = "    #[serde(skip_serializing_if = \"Tri::is_missing\")]\n";
        let no_skip = "    #[serde(default)]\n";
        let bad = [
            format!("{no_default}    pub a: Tri<String>,\n"),
            format!("{no_skip}    pub a: Tri<String>,\n"),
            "    pub a: Tri<String>,\n".to_owned(),
            format!("{attributes}\n    pub a: Tri<String>,\n"),
            format!("{no_skip}    pub(super) r#type: Tri<String>,\n"),
            format!("{no_skip}    pub a: crate::tri::Tri<String>,\n"),
            "    V { a: Tri<u8> },\n".to_owned(),
            "    V { #[serde(default)] a: Tri<u8> },\n".to_owned(),
        ];
        for source in &bad {
            assert_eq!(tri_fields_missing_attributes(source).len(), 1, "{source}");
        }
    }

    fn rust_files(directory: &Path, found: &mut Vec<PathBuf>) {
        for entry in std::fs::read_dir(directory).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                rust_files(&path, found);
            } else if path.extension().is_some_and(|extension| extension == "rs") {
                found.push(path);
            }
        }
    }

    #[test]
    fn every_tri_field_of_the_server_crates_carries_the_serde_attributes() {
        let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let mut files = Vec::new();
        for entry in std::fs::read_dir(&crates).unwrap() {
            let source = entry.unwrap().path().join("src");
            if source.is_dir() {
                rust_files(&source, &mut files);
            }
        }
        assert!(files.len() >= 20, "{} files", files.len());
        for file in files {
            let source = std::fs::read_to_string(&file).unwrap();
            let bad = tri_fields_missing_attributes(&source);
            assert!(bad.is_empty(), "{}: {bad:?}", file.display());
        }
    }
