import path from 'node:path';
import { cli, InputError, json, plainObject, problem, read, stringOption } from './common.mjs';
import { loadRegister } from './check-env.mjs';

const TITLES = {
  product: 'Product', programs: 'Programs', desktop: 'Desktop client', url_scheme: 'URL scheme', server_identity: 'Server identity',
  data_dir: 'Data directory', keyring: 'Keyring', env: 'Environment variables', user_agent: 'User agent', packages: 'Packages',
  legacy: 'Legacy values (read by importers only)',
};
const SKIPPED = ['schema', 'bindings'];

const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = value => '`' + cell(value) + '`';

function rows(value, prefix, result) {
  for (const [key, item] of Object.entries(value)) {
    const name = prefix ? `${prefix}.${key}` : key;
    if (plainObject(item)) rows(item, name, result);
    else result.push([name, Array.isArray(item) ? item.join(', ') : String(item)]);
  }
  return result;
}

export const DOC_PATH = 'docs/dev/identity.md';

// Pure: the same identity table and register always give the same text.
export function render(identity, register) {
  if (!plainObject(identity)) throw new InputError(problem('tools/identity.json', 1, 'expected an object'));
  const out = [
    '# Identity and environment names',
    '',
    '<!-- Generated by tools/identity/write-doc.mjs from tools/identity.json and tools/env-register.json. Do not edit by hand. -->',
    '',
    'Every name that a build or an installation of impluvium shows to the outside comes from one table, `tools/identity.json`.',
    'Every environment variable the project reads or declares is listed in the register, `tools/env-register.json`.',
    'CI checks that both agree with the code and that this page is up to date.',
    '',
    '## Change rule',
    '',
    'Values in the identity table change only with the approval of the maintainer, together with a note on existing installations.',
    'From the first public release candidate on, every change of a value is a breaking change.',
    'Bindings that tie a value to the place in the code that uses it follow the code freely.',
    '',
    '## Identity table',
    '',
  ];
  for (const [key, value] of Object.entries(identity)) {
    if (SKIPPED.includes(key)) continue;
    out.push(`### ${TITLES[key] ?? key}`, '', '| Key | Value |', '|---|---|');
    const entries = plainObject(value) ? rows(value, '', []) : [[key, String(value)]];
    for (const [name, text] of entries) out.push(`| ${code(name)} | ${code(text)} |`);
    out.push('');
  }
  out.push(
    '## Environment register',
    '',
    'Names owned by the project start with `IMPLUVIUM_`; names owned by a tool or a framework keep their standard form.',
    'Status is `active` (in use), `planned` (target name), `reserved` or `retired`. Evidence says whether project code reads the name or a tool or image does.',
    'Names ending in `*` stand for a family of names. Shell scripts are not scanned; the only product script reads no project variable.',
    '',
    '| Name | Kind | Component | Status | Evidence | Standard | Secret | Fate | Description |',
    '|---|---|---|---|---|---|---|---|---|',
  );
  for (const entry of register) {
    const fate = entry.fate.action === 'rename' ? `rename to ${code(entry.fate.to)}` : entry.fate.action;
    out.push(`| ${code(entry.name)} | ${entry.kind} | ${entry.component} | ${entry.status} | ${cell(entry.evidence)} | ${entry.standard ? 'yes' : 'no'} | ${entry.secret ? 'yes' : 'no'} | ${fate}: ${cell(entry.fate.when)} | ${cell(entry.description)} |`);
  }
  out.push('');
  return out.join('\n');
}

export function loadAndRender(root) {
  const identity = json(path.join(root, 'tools/identity.json'));
  return render(identity, loadRegister(path.join(root, 'tools/env-register.json')));
}

export function check(options) {
  if (!options.check) throw new InputError(problem('<arguments>', 1, '--check is required: this tool only compares; tools/identity/write-doc.mjs writes the page'));
  const root = path.resolve(options.root ?? '.');
  const expected = loadAndRender(root);
  const file = path.join(root, DOC_PATH);
  let actual;
  try {
    actual = read(file);
  } catch {
    return [problem(DOC_PATH, 1, 'missing; run node tools/identity/write-doc.mjs in the disposable container and commit the result')];
  }
  if (actual === expected) return [];
  const have = actual.split('\n');
  const want = expected.split('\n');
  let line = 0;
  while (line < Math.max(have.length, want.length) && have[line] === want[line]) line++;
  return [problem(DOC_PATH, line + 1, 'out of date with tools/identity.json and tools/env-register.json; regenerate it with tools/identity/write-doc.mjs')];
}

await cli(import.meta.url, `Usage: node tools/ci/identity-doc.mjs [--root DIR] --check
Render docs/dev/identity.md from tools/identity.json and tools/env-register.json and compare it with the committed page. Never writes;
tools/identity/write-doc.mjs writes the page with the same render function.
Exit: 0 up to date, 1 drift or missing page, 2 usage or input error.`, {
  root: stringOption, check: { type: 'boolean' },
}, check);
