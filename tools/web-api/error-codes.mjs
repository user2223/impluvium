// Writes or checks the client copy of the server error catalog:
// server/shared/api/error-codes.ts from
// server/crates/server-api-types/error-codes.json.
// Usage: node tools/web-api/error-codes.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
export const catalogFile = join(root, 'server/crates/server-api-types/error-codes.json');
export const clientFile = join(root, 'server/shared/api/error-codes.ts');

/** The client module for a catalog (an array of { code, status, message }). */
export function render(catalog) {
  if (!Array.isArray(catalog) || catalog.length === 0) throw new Error('the catalog must be a non-empty array');
  const rows = catalog.map(({ code, status }) => {
    if (typeof code !== 'string' || !/^[a-z_]+$/.test(code) || !Number.isInteger(status)) {
      throw new Error(`invalid catalog row: ${code}`);
    }
    return `  { code: ${JSON.stringify(code)}, status: ${status} },`;
  });
  return `// SPDX-FileCopyrightText: 2026 the impluvium contributors
// SPDX-License-Identifier: AGPL-3.0-only

// Generated by tools/web-api/error-codes.mjs from the server error catalog.
// Do not edit; a test fails when this file and the catalog differ.

export const errorCodes = [
${rows.join('\n')}
] as const;

export type ErrorCodeName = (typeof errorCodes)[number]["code"];

export const errorCodeNames: ReadonlySet<string> = new Set(
  errorCodes.map((entry) => entry.code),
);
`;
}

export function expected() {
  return render(JSON.parse(readFileSync(catalogFile, 'utf8')));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(clientFile, 'utf8') !== expected()) {
      console.error('server/shared/api/error-codes.ts differs from the server error catalog; run node tools/web-api/error-codes.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(clientFile, expected());
  }
}
