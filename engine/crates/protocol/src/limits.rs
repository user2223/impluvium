#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Kind {
    Uint32,
    Uint64,
    Int32,
    Int64,
    Bool,
    String,
    Bytes,
    Enum(&'static [(&'static str, i32)]),
    Message(MessageKind),
    Map { key: usize, value: usize },
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Occurrence {
    Scalar,
    Message,
    Repeated,
    Map,
    Oneof,
}

