export async function coverageGate(executed: {id:string;result:string}[], confirmationsPending:number):Promise<any> {
  const index=await readIndex(),table=await loadAsset('coverage.json',index),inventory=await loadAsset('field-inventory.json',index),schema=await loadAsset('schema.json',index);
  if(table.format!=='coverage-table-v1'||!Array.isArray(table.rows)||!table.rows.length)throw Error('invalid_coverage_table');
  const cases=new Map<string,any>();for(const group of index.groups)for(const entry of(await loadCorpus(group.file,group.sha256)).cases){if(cases.has(entry.id))throw Error('duplicate_coverage_case');cases.set(entry.id,entry);}
  if(table.caseIds.length!==cases.size||new Set(table.caseIds).size!==cases.size||table.caseIds.some((id:string)=>!cases.has(id)))throw Error('coverage_case_inventory');
  const fields:string[]=[];for(const[name,message]of Object.entries(schema.messages) as [string,any][]){for(const field of message.fields){fields.push(name+'.'+field.name);if(field.map)for(const part of['key','value'])fields.push(name+'.'+field.name+'.Entry.'+part);}}
  if(inventory.fields.length!==fields.length||table.fieldIds.length!==fields.length||new Set(table.fieldIds).size!==fields.length||fields.some(field=>!table.fieldIds.includes(field)||!inventory.fields.some((row:any)=>row.fieldId===field)))throw Error('coverage_field_inventory');
  for(const[name,message]of Object.entries(schema.messages) as [string,any][])for(const field of message.fields){const row=inventory.fields.find((row:any)=>row.fieldId===name+'.'+field.name);if(row.no!==field.no||row.type!==field.type||row.repeated!==!!field.repeated||row.map!==!!field.map)throw Error('coverage_field_position');if(field.map)for(const[number,part]of[[1,'key'],[2,'value']]){const entry=inventory.fields.find((row:any)=>row.fieldId===name+'.'+field.name+'.Entry.'+part);if(entry.no!==number||entry.parentNo!==field.no||entry.type!=='string')throw Error('coverage_map_position');}}
  const seenCases=new Set<number>(),seenFields=new Set<number>();
  const validCase=(id:number):void=>{if(!Number.isSafeInteger(id)||id<0||id>=table.caseIds.length)throw Error('coverage_case_reference');seenCases.add(id);};
  for(const row of table.rows){if(!table.rules[row.rule]||!row.codec||!row.level||!row.provenance||!row.checker||!row.consumer||![row.positive,row.negative,row.priority,row.fields].every(Array.isArray)||!row.positive.length&&!row.negative.length)throw Error('invalid_coverage_row');if(!selfCheckSourceFiles.includes(row.checker.split('#')[0]))throw Error('coverage_checker_reference');for(const id of[...row.positive,...row.negative,...row.priority])validCase(id);for(const id of row.fields){if(!Number.isSafeInteger(id)||id<0||id>=fields.length)throw Error('coverage_field_reference');seenFields.add(id);}}
  function contains(value:any,text:string):boolean{return value===text||!!value&&typeof value==='object'&&Object.values(value).some(item=>contains(item,text));}
  for(const row of table.reasonRows){if(!row.reason||!Array.isArray(row.cases)||!row.cases.length)throw Error('uncovered_reason');for(const id of row.cases){validCase(id);if(!contains(cases.get(table.caseIds[id]).expected,row.reason))throw Error('coverage_reason_witness');}}
  const limits=new Set<string>();
  for(const row of table.boundaryPairs){validCase(row.at);validCase(row.above);if(!table.fieldIds[row.field]||!['binary','json'].includes(row.codec))throw Error('coverage_boundary_reference');const[name,fieldName]=table.fieldIds[row.field].split('.'),field=schema.messages[name].fields.find((item:any)=>item.name===fieldName),bound=row.kind==='elements'?field.maxElements:row.kind==='key-bytes'?field.keyMaxBytes:row.kind==='value-bytes'?(field.map?field.valueMaxBytes:field.maxBytes):undefined;if(bound===undefined||row.limit!==String(bound))throw Error('coverage_boundary_limit');const at=cases.get(table.caseIds[row.at]),above=cases.get(table.caseIds[row.above]);if(at.expected.reason||above.expected.reason!==(row.kind==='elements'?'element_limit_exceeded':'byte_limit_exceeded'))throw Error('coverage_boundary_outcome');const key=row.field+':'+row.codec+':'+row.kind;if(limits.has(key))throw Error('duplicate_coverage_boundary');limits.add(key);}
  for(const[name,message]of Object.entries(schema.messages) as [string,any][])for(const field of message.fields){const position=table.fieldIds.indexOf(name+'.'+field.name),kinds=[...(field.maxElements!==undefined?['elements']:[]),...(field.maxBytes!==undefined?['value-bytes']:[]),...(field.map?['key-bytes','value-bytes']:[])];for(const kind of kinds)for(const codec of['binary','json'])if(!limits.has(position+':'+codec+':'+kind))throw Error('uncovered_field_boundary');}
  const aggregateLimits:Record<string,string>={'manifest-envelope':'536887296','descriptor-envelope':'1064960','small-envelope':'4096','rpc-request':'65536','auth-success':'65536','device-success':'1048576','library-success':'4194304','download-success':'2097152','envelope-manifest-payload':'536870912','envelope-descriptor-payload':'1048576','envelope-metadata':'16384','command-bytes':'262144','http1-head':'65536','http2-head':'65536'};
  const aggregateNames=new Set<string>();for(const row of table.aggregatePairs){validCase(row.at);validCase(row.above);if(aggregateLimits[row.name]!==row.limit||!row.level||aggregateNames.has(row.name))throw Error('coverage_aggregate_reference');aggregateNames.add(row.name);const at=cases.get(table.caseIds[row.at]).expected,above=cases.get(table.caseIds[row.above]).expected;if(!(at.accepted===true||at.sizeAccepted===true||at.decision==='accept')||typeof above.reason!=='string')throw Error('coverage_aggregate_witness');}if(aggregateNames.size!==Object.keys(aggregateLimits).length)throw Error('uncovered_aggregate_boundary');
  if(!Array.isArray(table.unreachable)||!table.unreachable.length)throw Error('missing_unreachable_inventory');for(const row of table.unreachable)if(!row.scope||!row.rule||!row.explanation||row.fields?.some((field:string)=>!table.fieldIds.includes(field)))throw Error('invalid_unreachable_inventory');
  const seenReasons=new Set(table.reasonRows.map((row:any)=>row.reason));if(seenReasons.size!==table.reasonRows.length||seenReasons.size!==localReasons.length||localReasons.some(reason=>!seenReasons.has(reason)))throw Error('coverage_reason_inventory');
  if(seenCases.size!==cases.size||seenFields.size!==fields.length)throw Error('coverage_unmapped_inventory');
  if(createHash('sha256').update(await readDataBytes('coverage.md')).digest('hex')!==table.readableSha256)throw Error('coverage_readable_integrity');
  const execution=new Map<string,string>();for(const row of executed){if(execution.has(row.id))throw Error('duplicate_case_execution');execution.set(row.id,row.result);}
  const outstanding=table.caseIds.filter((id:string)=>execution.get(id)!=='pass').map((id:string)=>({id,state:execution.get(id)??'not-executed'}));
  return{format:'coverage-contract-v3',rows:table.rows.length,cases:cases.size,schemaFields:fields.length,reasons:seenReasons.size,boundaryPairs:table.boundaryPairs.length,aggregatePairs:table.aggregatePairs.length,passed:cases.size-outstanding.length,outstanding,confirmationsPending,specificationConditions:index.blocked,complete:outstanding.length===0&&confirmationsPending===0&&index.blocked.length===0};
}
